"""Running OVS programs under valgrind, helgrind or strace.

With ``--valgrind``, ``--helgrind`` or ``--strace``, the wrapper scripts in
``tests/valgrind`` of the build directory, generated by the Makefile from
``tests/valgrind-wrapper.in``, are put first in ``PATH``.  They shadow the
OVS programs and run them under the command in the ``VALGRIND`` environment
variable.  This works the same way for the pytest-based tests and for the
Autotest tests, as it always did for 'make check-valgrind'.

The command can be overridden by setting ``VALGRIND`` in the environment,
which the Makefile does.  Every program writes its output to
``valgrind.<pid>``, ``helgrind.<pid>`` or ``strace.<pid>`` (one per thread)
in the directory of the test.  Tests don't fail because of the reported errors,
but artifacts of all the tests are kept, and the files with errors are
listed at the end of the run.
"""

import glob
import os
import re
import shutil

from tests.lib import env

_SUPPRESSIONS = ("glibc.supp", "openssl.supp")

# Same as VALGRIND and HELGRIND in tests/automake.mk.
_COMMANDS = {
    "valgrind": "valgrind --log-file=valgrind.%p --leak-check=full "
                "--track-origins=yes {supp} --num-callers=20",
    "helgrind": "valgrind --log-file=helgrind.%p --tool=helgrind "
                "{supp} --num-callers=20",
    # With -ff, strace writes the output of every process and thread to
    # strace.<pid>.  With -D, strace is not the parent of the program, so
    # the command returns when a daemon detaches, as without strace.
    "strace": "strace -D -ff -tt -o strace",
}

_ERROR_SUMMARY = re.compile(r"ERROR SUMMARY: ([1-9][0-9]*) errors")


def pytest_addoption(parser):
    group = parser.getgroup("ovs-tools", "running OVS programs under tools")
    for tool in sorted(_COMMANDS):
        group.addoption("--" + tool, action="store_true", default=False,
                        help="Run OVS programs under %s." % tool)


def selected(config):
    """Return the name of the selected tool, or None."""
    tools = [t for t in sorted(_COMMANDS) if config.getoption(t)]
    if len(tools) > 1:
        raise ValueError("options %s are mutually exclusive"
                         % ", ".join("--" + t for t in tools))
    return tools[0] if tools else None


def command(tool):
    """Return the default command line for running programs under ``tool``.
    """
    supp = " ".join("--suppressions=" + os.path.join(env.srcdir(), "tests", s)
                    for s in _SUPPRESSIONS)
    return _COMMANDS[tool].format(supp=supp)


def wrappers_dir():
    return os.path.join(env.builddir(), "tests", "valgrind")


def configure(config):
    """Set up the environment for the selected tool, if any.

    Must run before ``env.setup()``, which puts ``AUTOTEST_PATH`` into
    ``PATH``.  Returns an error message, or None.
    """
    try:
        tool = selected(config)
    except ValueError as e:
        return str(e)
    if tool is None:
        return None

    program = "strace" if tool == "strace" else "valgrind"
    if shutil.which(program) is None:
        return "%s is not installed" % program
    if not os.path.isfile(os.path.join(wrappers_dir(), "ovs-vswitchd")):
        return ("wrapper scripts are not found in %s, run "
                "'make check-valgrind' or build them with 'make "
                "tests/valgrind/ovs-vswitchd' and friends" % wrappers_dir())

    if not os.environ.get("VALGRIND"):
        os.environ["VALGRIND"] = command(tool)
    # The wrapper scripts must come first, before the programs they shadow.
    # pytest-xdist workers inherit the environment of the controller, where
    # this is done already.
    path = os.environ.get("AUTOTEST_PATH", env.DEFAULT_AUTOTEST_PATH)
    if path.split(":")[0] != wrappers_dir():
        os.environ["AUTOTEST_PATH"] = wrappers_dir() + ":" + path
    # Outputs of passed tests may have errors too.
    config.option.keep_artifacts = True
    return None


def reports(dirs, tool):
    """Return the paths of ``tool`` outputs with errors under ``dirs``."""
    if tool == "strace":
        return []
    found = []
    for d in dirs:
        for path in glob.glob(os.path.join(d, "**", tool + ".*"),
                              recursive=True):
            try:
                with open(path, errors="replace") as f:
                    if _ERROR_SUMMARY.search(f.read()):
                        found.append(path)
            except OSError:
                pass
    return sorted(found)
